#!/usr/bin/env python3
"""Reproduce CMS revocation snapshot/annual catheter cohort reconciliation.

Only public CMS sources. Main snapshot excludes names/contact details. Known-case
lookups include legal business names. Output intersections are aggregate only.
No adverse conclusion or payment-recovery estimate is generated by this program.
"""
from __future__ import annotations
import argparse
import csv
import datetime as dt
from decimal import Decimal as D
import hashlib
import io
import json
from pathlib import Path
import urllib.parse
import urllib.request

BASE = Path(__file__).resolve().parent
COHORT = BASE.parent / "data-audit" / "snapshots"
CATALOG = "https://data.cms.gov/data.json"
FIELDS = ["ENRLMT_ID", "NPI", "MULTIPLE_NPI_FLAG", "STATE_CD", "PROVIDER_TYPE_DESC",
          "REVOCATION_RSN", "REVOCATION_EFCTV_DT", "REENROLLMENT_BAR_EXPRTN_DT"]
KNOWN = {"nd_medical": "1790533503", "centennial": "1609626167"}

def sha(b): return hashlib.sha256(b).hexdigest()
def save(name, obj):
    p = BASE / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n")
def load(name): return json.loads((BASE / name).read_text())

def get(url, kind="json"):
    started = dt.datetime.now(dt.timezone.utc).isoformat()
    req = urllib.request.Request(url, headers={"User-Agent": "Pipemind-public-enrollment-audit/1.0"})
    with urllib.request.urlopen(req, timeout=30) as response:
        b = response.read()
        meta = {"url": url, "retrieved_at": started, "status": response.status,
                "wire_response_sha256": sha(b), "bytes": len(b),
                "content_type": response.headers.get("Content-Type"),
                "last_modified": response.headers.get("Last-Modified")}
    if kind == "json": return json.loads(b), meta
    return b, meta

def acquire():
    catalog, catalog_meta = get(CATALOG)
    candidates = [x for x in catalog["dataset"] if x.get("title", "").startswith("Revoked Medicare Providers and Suppliers :")]
    if len(candidates) != 1: raise ValueError("Catalog needs manual selection; unexpected matching datasets")
    cat = candidates[0]
    series = next(x for x in cat["distribution"] if x.get("description") == "latest")
    immutable = next(x for x in cat["distribution"] if x.get("format") == "API" and x.get("description") != "latest")
    root = immutable["accessURL"].removesuffix("/data")
    resources, resource_meta = get(immutable["resourcesAPI"])
    dictionary, dictionary_meta = get(root + "/dictionary")
    save("catalog_selected.json", cat)
    save("resources.json", resources)
    save("dictionary.json", dictionary)
    stats, stats_meta = get(root + "/data/stats")
    rows, pages, offset = [], [], 0
    while True:
        params = {"column": ",".join(FIELDS), "sort": "ENRLMT_ID", "size": 5000, "offset": offset}
        page, meta = get(root + "/data?" + urllib.parse.urlencode(params))
        if not isinstance(page, list): raise ValueError("Unexpected API response")
        meta.update({"returned_rows": len(page), "offset": offset})
        pages.append(meta)
        if not page: break
        rows.extend(page)
        offset += len(page)
    if len(rows) != int(stats["found_rows"]): raise ValueError("Incomplete source paging")
    if any(set(row) != set(FIELDS) for row in rows): raise ValueError("Unexpected source fields")
    rows.sort(key=lambda r: (r["ENRLMT_ID"], r["NPI"]))
    save("snapshots/revoked_selected.json", rows)
    additional_resource = next(x for x in resources["data"] if x["name"].startswith("Additional NPIs"))
    raw, additional_meta = get(additional_resource["downloadURL"], "bytes")
    additional = list(csv.DictReader(io.StringIO(raw.decode("utf-8-sig"))))
    if any(set(r) != {"ENRLMT_ID", "NPI"} for r in additional): raise ValueError("Unexpected additional NPI schema")
    save("snapshots/additional_npis.json", additional)
    known, known_meta = {}, {}
    for key, npi in KNOWN.items():
        params = {"filter[NPI]": npi, "column": ",".join(FIELDS + ["ORG_NAME"]), "size": 5000}
        known[key], known_meta[key] = get(root + "/data?" + urllib.parse.urlencode(params))
        if any(r["NPI"] != npi for r in known[key]): raise ValueError("Exact NPI filter failure")
    save("snapshots/known_case_matches.json", known)
    snapshots = ["snapshots/revoked_selected.json", "snapshots/additional_npis.json", "snapshots/known_case_matches.json"]
    manifest = {"catalog_request": catalog_meta, "title": cat["title"], "modified": cat["modified"],
                "temporal": cat.get("temporal"), "immutable_data_root": root,
                "series_data_url": series["accessURL"], "resource_request": resource_meta,
                "dictionary_request": dictionary_meta, "stats": stats, "stats_request": stats_meta,
                "main_pages": pages, "selected_columns": FIELDS,
                "additional_request": additional_meta, "known_case_requests": known_meta,
                "snapshots": {p: {"sha256": sha((BASE / p).read_bytes())} for p in snapshots},
                "hash_scope": "Wire hashes cover exact fetched responses, including API column projection; snapshot hashes cover saved JSON transformation. Catalog hash covers full source while catalog_selected.json contains only the selected dataset.",
                "freshness_limit": "Publication metadata and a quarterly extract; neither real-time PECOS status nor a claim-level payment ledger."}
    save("acquisition_manifest.json", manifest)

def relation(year, effective):
    date = dt.date.fromisoformat(effective)
    if date < dt.date(year, 1, 1): return "effective_before_service_year"
    if date > dt.date(year, 12, 31): return "effective_after_service_year"
    return "effective_during_service_year"

def reconcile():
    main = load("snapshots/revoked_selected.json")
    extra = load("snapshots/additional_npis.json")
    manifest = load("acquisition_manifest.json")
    by_enrollment = {}
    for r in main: by_enrollment.setdefault(r["ENRLMT_ID"], []).append(r)
    flattened = {(r["ENRLMT_ID"], r["NPI"]): dict(r) for r in main}
    orphans = []
    for x in extra:
        if x["ENRLMT_ID"] not in by_enrollment:
            orphans.append(x)
            continue
        for original in by_enrollment[x["ENRLMT_ID"]]:
            r = dict(original)
            r["NPI"] = x["NPI"]
            flattened[(r["ENRLMT_ID"], r["NPI"])] = r
    by_npi = {}
    for r in flattened.values():
        if r["NPI"]: by_npi.setdefault(r["NPI"], []).append(r)
    cohorts, input_hashes, union_cohort, union_matches = [], {}, set(), set()
    for year in (2022, 2023, 2024):
        year_rows = []
        for code in ("A4351", "A4352", "A4353"):
            p = COHORT / f"suppliers_{year}_{code}.json"
            input_hashes[str(p.relative_to(BASE.parent))] = sha(p.read_bytes())
            year_rows.extend(json.loads(p.read_text()))
        for code in ("A4351", "A4352", "A4353", "ALL_THREE_CODES"):
            rows = year_rows if code == "ALL_THREE_CODES" else [r for r in year_rows if r["HCPCS_Cd"] == code]
            npis = {r["Suplr_NPI"] for r in rows}
            matches = npis & set(by_npi)
            union_cohort.update(npis)
            union_matches.update(matches)
            # One supplier can have multiple enrollment dates. Relation buckets count
            # unique NPI per relation and need not sum to the number of matched NPIs.
            relations = {}
            for rel in ("effective_before_service_year", "effective_during_service_year", "effective_after_service_year"):
                targets = {npi for npi in matches if any(relation(year, r["REVOCATION_EFCTV_DT"]) == rel for r in by_npi[npi])}
                amount = sum((D(r["Tot_Suplr_Srvcs"]) * D(r["Avg_Suplr_Mdcr_Pymt_Amt"]) for r in rows if r["Suplr_NPI"] in targets), D(0))
                relations[rel] = {"unique_npis": len(targets), "associated_annual_puf_payment_measure_usd": str(amount.quantize(D("0.01")))}
            cohorts.append({"year": year, "code": code, "cohort_unique_npis": len(npis),
                            "matches_to_current_revocation_snapshot_unique_npis": len(matches),
                            "timing_relations": relations})
    known = load("snapshots/known_case_matches.json")
    known_presence = {}
    for name, npi in KNOWN.items():
        hits = []
        for year in (2022, 2023, 2024):
            for code in ("A4351", "A4352", "A4353"):
                p = COHORT / f"suppliers_{year}_{code}.json"
                rows = [r for r in json.loads(p.read_text()) if r["Suplr_NPI"] == npi]
                if rows:
                    hits.append({"year": year, "code": code, "rows": len(rows), "revocation_effective_dates": sorted({r["REVOCATION_EFCTV_DT"] for r in known[name]}),
                                 "associated_annual_puf_payment_measure_usd": str(sum((D(r["Tot_Suplr_Srvcs"]) * D(r["Avg_Suplr_Mdcr_Pymt_Amt"]) for r in rows), D(0)).quantize(D("0.01")))})
        known_presence[name] = {"npi": npi, "published_rows": hits, "absence_is_not_evidence_of_no_billing": True}
    result = {"main_rows": len(main), "main_unique_enrollment_npi_keys": len({(r["ENRLMT_ID"], r["NPI"]) for r in main}),
              "main_unique_enrollments": len(by_enrollment), "main_blank_npi_rows": sum(not r["NPI"] for r in main),
              "additional_npi_rows": len(extra), "additional_orphan_rows": len(orphans),
              "flattened_enrollment_npi_rows_including_blanks": len(flattened), "flattened_unique_nonblank_npis": len(by_npi),
              "cohort_unique_npis_across_years_and_codes": len(union_cohort), "unique_cohort_npis_matching_current_snapshot": len(union_matches),
              "cohort_input_sha256": input_hashes, "cohorts": cohorts, "known_case_puf_presence": known_presence,
              "interpretation": [
                  "Exact NPI linkage only; current snapshot is not historical enrollment status.",
                  "Annual PUF service-year measures cannot establish transaction payment dates or released cash.",
                  "A revocation effective during a year does not place that year's services before or after the effective date.",
                  "A current revoked enrollment may coexist with another active enrollment under the same TIN; NPI linkage alone does not identify the billed enrollment.",
                  "The current-bar snapshot omits completed bars, appeal outcomes and other historically relevant records; matching share is not a fraud or revocation rate.",
                  "Relation buckets can overlap for an NPI with more than one revoked enrollment; do not sum them.",
                  "No new named suspected actor or alleged loss is emitted."],
              "validation": {"stats_row_count_equal": len(main) == int(manifest["stats"]["found_rows"]),
                             "main_enrollment_npi_keys_unique": len(main) == len({(r["ENRLMT_ID"], r["NPI"]) for r in main}),
                             "additional_enrollment_npi_keys_unique": len(extra) == len({(r["ENRLMT_ID"], r["NPI"]) for r in extra}),
                             "terminal_empty_page": manifest["main_pages"][-1]["returned_rows"] == 0,
                             "additional_all_enrollments_linked": not orphans}}
    save("crosscheck.json", result)
    validate()
    return result

def validate():
    manifest, result = load("acquisition_manifest.json"), load("crosscheck.json")
    assert all(result["validation"].values())
    for p, expected in manifest["snapshots"].items(): assert sha((BASE / p).read_bytes()) == expected["sha256"], p
    for p, expected in result["cohort_input_sha256"].items(): assert sha((BASE.parent / p).read_bytes()) == expected, p
    assert relation(2024, "2025-04-23") == "effective_after_service_year"
    assert relation(2024, "2024-01-01") == "effective_during_service_year"
    assert relation(2024, "2024-12-31") == "effective_during_service_year"
    assert relation(2024, "2023-12-31") == "effective_before_service_year"
    matches = load("snapshots/known_case_matches.json")
    for key, records in matches.items():
        assert all(r["NPI"] == KNOWN[key] for r in records)
        for r in records:
            assert dt.date.fromisoformat(r["REENROLLMENT_BAR_EXPRTN_DT"]) >= dt.date.fromisoformat(r["REVOCATION_EFCTV_DT"])
    print(json.dumps({"validation": "passed", "main_rows": result["main_rows"], "additional_rows": result["additional_npi_rows"], "cohort_matches": result["unique_cohort_npis_matching_current_snapshot"]}))

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--acquire", action="store_true", help="Refetch official current catalog and snapshot; then reconcile")
    p.add_argument("--validate", action="store_true", help="Offline hashes, paging evidence and date-boundary checks")
    args = p.parse_args()
    if args.validate: validate()
    else:
        if args.acquire: acquire()
        reconcile()
